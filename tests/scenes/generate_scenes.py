def scene_forest_path():
    rnd = random.Random(9)
    L = head("Stylized forest path", (0, 3.5, -20), (0, 3, 0), 62,
             (0.35, 0.55, 0.35), (0.95, 0.75, 0.35))
    L.append("light_source { <8, 25, -10> color " + c(1.0, 0.9, 0.55) + " }")
    L.append("light_source { <-12, 8, 4> color " + c(0.3, 0.6, 0.35) + " }")
    L.append("plane { y, 0 texture { pigment { gradient x color_map { [0.0 color " + c(0.05,0.25,0.08) + "] [0.5 color " + c(0.15,0.5,0.12) + "] [1.0 color " + c(0.05,0.2,0.06) + "] } } finish { diffuse 0.7 } } }")
    # winding path
    for i in range(18):
        z = -18 + i * 2.0
        x = 2.5 * math.sin(z * 0.12)
        L.append(f"box {{ {v(x-1.6,0.01,z-0.9)}, {v(x+1.6,0.05,z+0.9)} texture {{ pigment {{ color {c(0.75,0.6,0.35)} }} finish {{ diffuse 0.8 }} }} }}")
    # trees
    for i in range(16):
        side = -1 if i % 2 == 0 else 1
        x = side * (5 + rnd.uniform(0, 8))
        z = -16 + rnd.uniform(0, 30)
        h = rnd.uniform(4, 8)
        trunk = (0.25, 0.15, 0.08)
        leaf = [(0.08,0.55,0.15), (0.25,0.7,0.1), (0.7,0.65,0.08), (0.15,0.45,0.25)][i % 4]
        L.append(f"cylinder {{ {v(x,0,z)}, {v(x,h*0.6,z)}, 0.25 texture {{ pigment {{ color {c(*trunk)} }} finish {{ diffuse 0.8 }} }} }}")
        L.append(f"cone {{ {v(x,h*0.35,z)}, 1.7, {v(x,h,z)}, 0.15 texture {{ pigment {{ color {c(*leaf)} }} finish {{ diffuse 0.6 }} }} }}")
        L.append(f"cone {{ {v(x,h*0.55,z)}, 1.3, {v(x,h*1.15,z)}, 0.1 texture {{ pigment {{ color {c(leaf[0]*1.2,leaf[1]*1.2,leaf[2]*1.2)} }} finish {{ diffuse 0.6 }} }} }}")
    # fireflies
    for i in range(30):
        x = rnd.uniform(-12, 12); y = rnd.uniform(0.5, 4.0); z = rnd.uniform(-10, 15)
        L.append(f"sphere {{ {v(x,y,z)}, 0.08 " + emissive(1.0, 0.9, 0.3) + " }")
    # distant hills
    L.append("sphere { <0,-8,30>, 18 scale <2.5,0.5,1.0> texture { pigment { color " + c(0.1,0.3,0.15) + " } finish { diffuse 0.7 } } }")
    write("10_forest_path.pov", L)


