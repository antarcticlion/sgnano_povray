    L.append("torus { 9.0, 0.75 rotate <18,0,12> " + metal(0.72,0.78,0.88) + " }")
    L.append("torus { 9.0, 0.18 rotate <18,0,12> translate <0,0.75,0> " + emissive(0.1,0.75,1.0) + " }")
