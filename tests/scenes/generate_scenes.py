#!/usr/bin/env python3
"""Generate the 10 POV-Ray test scenes in this directory.

The scenes are deliberately self-contained (no external includes) and use
vivid sRGB colours. They are meant for rendering with the sgnano POV-Ray port
and for exercising checkpoint/resume.
"""
import math
import os
import random

OUT = os.path.dirname(os.path.abspath(__file__))


def v(x, y, z):
    return f"<{x:.3f}, {y:.3f}, {z:.3f}>"


def c(r, g, b):
    return f"srgb <{r:.3f}, {g:.3f}, {b:.3f}>"


def ct(r, g, b, t):
    return f"rgbt <{r:.3f}, {g:.3f}, {b:.3f}, {t:.3f}>"


def tex(r, g, b, finish="diffuse 0.65 specular 0.35 roughness 0.04"):
    return f"texture {{ pigment {{ color {c(r, g, b)} }} finish {{ {finish} }} }}"


def emissive(r, g, b):
    return f"texture {{ pigment {{ color {c(r, g, b)} }} finish {{ ambient 1 diffuse 0 }} }}"


def metal(r, g, b):
    return tex(r, g, b, "diffuse 0.18 specular 0.9 roughness 0.015 reflection { 0.55 }")


def glass(r, g, b, t=0.65):
    # interior は texture の中ではなく、オブジェクトの修飾として付ける。
    return (f"texture {{ pigment {{ color {ct(r, g, b, t)} }} "
            f"finish {{ specular 0.9 roughness 0.015 reflection {{ 0.18 }} }} }}")


def head(title, cam, look, angle, sky_top, sky_bottom):
    return [
        f"// {title}",
        "// Generated by tests/scenes/generate_scenes.py",
        "#version 3.7;",
        "global_settings { assumed_gamma 1.0 }",
        f"camera {{ location {v(*cam)} look_at {v(*look)} angle {angle} }}",
        "sky_sphere { pigment { gradient y color_map {",
        f"  [0.0 color {c(*sky_bottom)}]",
        f"  [1.0 color {c(*sky_top)}]",
        "} } }",
    ]


def write(name, lines):
    path = os.path.join(OUT, name)
    with open(path, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(name, len(lines), "lines")


def terrain(nx, nz, sx, sz, height, tex_line):
    lines = ["mesh {"]
    for i in range(nx):
        for j in range(nz):
            x0 = -sx / 2 + sx * i / nx
            x1 = -sx / 2 + sx * (i + 1) / nx
            z0 = -sz / 2 + sz * j / nz
            z1 = -sz / 2 + sz * (j + 1) / nz
            p00 = (x0, height(x0, z0), z0)
            p10 = (x1, height(x1, z0), z0)
            p01 = (x0, height(x0, z1), z1)
            p11 = (x1, height(x1, z1), z1)
            lines.append(f"  triangle {{ {v(*p00)}, {v(*p10)}, {v(*p01)} }}")
            lines.append(f"  triangle {{ {v(*p10)}, {v(*p11)}, {v(*p01)} }}")
    lines.append("  " + tex_line)
    lines.append("}")
    return lines


def mesh_quad(points, tex_line, extra=""):
    # points: 8 corners, bottom 0-3, top 4-7
    faces = [
        (0, 1, 2), (0, 2, 3),       # bottom
        (4, 6, 5), (4, 7, 6),       # top
        (0, 4, 5), (0, 5, 1),       # front
        (1, 5, 6), (1, 6, 2),       # right
        (2, 6, 7), (2, 7, 3),       # back
        (3, 7, 4), (3, 4, 0),       # left
    ]
    lines = ["mesh {"]
    for a, b, cidx in faces:
        lines.append(f"  triangle {{ {v(*points[a])}, {v(*points[b])}, {v(*points[cidx])} }}")
    lines.append("  " + tex_line + ((" " + extra) if extra else ""))
    lines.append("}")
    return lines


