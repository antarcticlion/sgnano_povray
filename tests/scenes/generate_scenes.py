def scene_space_station():
    rnd = random.Random(7)
    L = head("Orbital ring station", (0, 6, -28), (0, 0, 0), 52,
             (0.0, 0.0, 0.02), (0.04, 0.02, 0.10))
    L.append("light_source { <20, 18, -20> color " + c(0.85, 0.92, 1.0) + " }")
    L.append("light_source { <-15, -10, 5> color " + c(1.0, 0.35, 0.15) + " }")
    # starfield
    for i in range(120):
        # random on a sphere
        u = rnd.uniform(0, 1); theta = 2 * math.pi * rnd.random()
        r = 60
        x = r * math.sqrt(1 - u * u) * math.cos(theta)
        y = r * u
        z = r * math.sqrt(1 - u * u) * math.sin(theta)
        b = rnd.uniform(0.5, 1.0)
        L.append(f"sphere {{ {v(x,y,z)}, {rnd.uniform(0.08,0.18)} {emissive(b,b,b)} }}")
