def scene_slow_spheres():
    """Deliberately heavy scene: many objects, reflections and glass.

    At 640x480 this should take minutes even on a fast host, and much longer on
    the RP2350. At 160x120 it should still be usable as a slow test.
    """
    L = head("Slow sphere field", (0, 14, -34), (0, 4, 0), 55,
             (0.02, 0.02, 0.08), (0.65, 0.18, 0.35))
    L.append("global_settings { max_trace_level 8 }")
    L.append("light_source { <18, 30, -22> color " + c(1.0, 0.9, 0.7) + " }")
    L.append("light_source { <-20, 14, 8> color " + c(0.25, 0.55, 1.0) + " }")
    L.append("light_source { <0, 8, 20> color " + c(1.0, 0.2, 0.45) + " }")
    L.append("plane { y, 0 texture { pigment { color " + c(0.015, 0.018, 0.025) + " } "
             "finish { diffuse 0.08 specular 0.95 roughness 0.005 reflection { 0.7 } } } }")
    # 10,000 spheres generated by the SDL parser. The reflective floor and
    # glass spheres multiply the ray work; 640x480 should take minutes.
    L.append("#declare IX = 0;")
    L.append("#while (IX < 100)")
    L.append("  #declare IZ = 0;")
    L.append("  #while (IZ < 100)")
    L.append("    #declare PX = (IX - 49.5) * 0.62;")
    L.append("    #declare PZ = (IZ - 49.5) * 0.62;")
    L.append("    #declare PY = 0.55 + mod(IX + IZ, 5) * 0.12;")
    L.append("    #declare RR = 0.5 + 0.5*sin(IX*0.31);")
    L.append("    #declare GG = 0.5 + 0.5*sin(IZ*0.27 + 1.0);")
    L.append("    #declare BB = 0.5 + 0.5*sin((IX+IZ)*0.19 + 2.0);")
    L.append("    #if (mod(IX*100 + IZ, 23) = 0)")
    L.append("      sphere { <PX,PY,PZ>, 0.28 texture { pigment { color rgbt <RR,GG,0.95,0.55> } finish { specular 1.0 roughness 0.01 reflection { 0.35 } } } interior { ior 1.5 } }")
    L.append("    #else")
    L.append("      sphere { <PX,PY,PZ>, 0.28 texture { pigment { color srgb <RR,GG,BB> } finish { diffuse 0.35 specular 0.8 roughness 0.02 reflection { 0.18 } } } }")
    L.append("    #end")
    L.append("    #declare IZ = IZ + 1;")
    L.append("  #end")
    L.append("  #declare IX = IX + 1;")
    L.append("#end")
    write("11_slow_spheres.pov", L)


def scene_geo_landscape():
    L = head("Geometric landscape", (0, 18, -42), (0, 4, 0), 55,
             (0.08, 0.12, 0.35), (1.0, 0.45, 0.18))
    L.append("light_source { <30, 35, -55> color " + c(1.0, 0.55, 0.25) + " }")
    L.append("light_source { <-25, 18, 10> color " + c(0.3, 0.55, 1.0) + " }")

    def h(x, z):
        return 4.0 * math.sin(x * 0.13) * math.cos(z * 0.11) + 1.5 * math.sin((x + z) * 0.21) + 2.0

    L += terrain(24, 24, 80, 80, h,
                 "texture { pigment { gradient y color_map { "
                 "[0.0 color " + c(0.10, 0.75, 0.65) + "] "
                 "[0.45 color " + c(0.85, 0.15, 0.75) + "] "
                 "[0.75 color " + c(1.0, 0.55, 0.15) + "] "
                 "[1.0 color " + c(1.0, 0.95, 0.55) + "] } } "
                 "finish { diffuse 0.55 specular 0.1 roughness 0.1 } }")
    L.append("plane { y, 0 texture { pigment { color " + c(0.02, 0.18, 0.30) + " } "
             "finish { diffuse 0.15 specular 0.8 roughness 0.02 reflection { 0.45 } } } }")
    L.append("sphere { <32, 28, -60>, 6 texture { pigment { color " + c(1.0, 0.75, 0.25) + " } "
             "finish { ambient 1 diffuse 0 } } }")

    shapes = [
        ("torus", 2.8, 0.55, (-10, 8, 4), (25, 30, 0), metal(0.9, 0.9, 1.0)),
        ("sphere", 2.2, 0, (8, 7, 0), (0, 0, 0), tex(1.0, 0.15, 0.45, "diffuse 0.4 specular 0.6 roughness 0.02 reflection { 0.2 }")),
        ("box", 0, 0, (14, 6, 8), (15, 35, 10), tex(0.15, 0.95, 0.85, "diffuse 0.4 specular 0.5 roughness 0.03")),
        ("torus", 3.5, 0.35, (-16, 6, -3), (70, 10, 20), tex(1.0, 0.9, 0.2, "diffuse 0.3 specular 0.7 roughness 0.02")),
    ]
    for kind, a, b, pos, rot, t in shapes:
        if kind == "torus":
            L.append(f"torus {{ {a}, {b} rotate {v(*rot)} translate {v(*pos)} {t} }}")
        elif kind == "sphere":
            L.append(f"sphere {{ {v(*pos)}, {a} {t} }}")
        else:
            L.append(f"box {{ {v(pos[0]-2,pos[1]-2,pos[2]-2)}, {v(pos[0]+2,pos[1]+2,pos[2]+2)} rotate {v(*rot)} {t} }}")
    write("01_geo_landscape.pov", L)


