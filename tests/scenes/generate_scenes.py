def scene_city_night():
    rnd = random.Random(4)
    L = head("Neon city at night", (0, 8, -34), (0, 12, 0), 62,
             (0.01, 0.01, 0.05), (0.18, 0.02, 0.25))
    L.append("light_source { <-18, 18, -10> color " + c(0.9, 0.15, 0.8) + " }")
    L.append("light_source { <20, 14, 5> color " + c(0.1, 0.75, 1.0) + " }")
    L.append("light_source { <0, 30, -20> color " + c(0.5, 0.55, 1.0) + " }")
    L.append("plane { y, 0 texture { pigment { color " + c(0.015, 0.02, 0.04) + " } "
             "finish { diffuse 0.1 specular 0.9 roughness 0.01 reflection { 0.55 } } } }")

    # towers
    for i in range(12):
        x = -26 + i * 4.6
        z = -8 + (i % 3) * 5
        h = 10 + rnd.random() * 26
        w = 2.6 + rnd.random() * 0.8
        shade = 0.04 + 0.03 * (i % 3)
        L.append(f"box {{ {v(x-w/2,0,z-2)}, {v(x+w/2,h,z+2)} texture {{ pigment {{ color {c(shade,shade+0.02,shade+0.06)} }} finish {{ diffuse 0.3 specular 0.5 roughness 0.05 }} }} }}")
        # windows: 3 columns x 6 rows
        for col in range(3):
            for row in range(6):
                if rnd.random() < 0.35:
                    continue
                wx = x - w/2 + 0.45 + col * (w-0.9)/2
                wy = 2.0 + row * (h - 3.5) / 6
                color = (1.0, 0.75, 0.25) if (i + row) % 3 else (0.2, 0.9, 1.0)
                L.append(f"box {{ {v(wx-0.18,wy-0.18,z+2.02)}, {v(wx+0.18,wy+0.18,z+2.10)} {emissive(*color)} }}")
        # roof antenna
        L.append(f"cylinder {{ {v(x,h,z)}, {v(x,h+2.5,z)}, 0.08 {emissive(1.0,0.1,0.2)} }}")
    # neon signs
    for x, color in [(-15, (1.0,0.1,0.6)), (-4, (0.1,0.9,1.0)), (8, (1.0,0.8,0.1)), (18, (0.7,0.2,1.0))]:
        L.append(f"box {{ {v(x-2.2,4.0,-4.8)}, {v(x+2.2,4.8,-4.6)} {emissive(*color)} }}")
        L.append(f"cylinder {{ {v(x,4.8,-4.7)}, {v(x,8.0,-4.7)}, 0.06 {metal(0.2,0.2,0.25)} }}")
    # reflection puddles
    for x in (-18, -7, 5, 16):
        L.append(f"cylinder {{ {v(x,0.01,-3)}, {v(x,0.02,-3)}, 2.5 pigment {{ color {ct(0.1,0.4,0.6,0.55)} }} finish {{ reflection {{ 0.6 }} }} }}")
    write("04_city_night.pov", L)


